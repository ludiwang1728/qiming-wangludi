-- 1. 起名历史表
create table if not exists public.name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,           -- 用户的起名需求
  name_result text not null,                -- AI 生成的 3 组名字方案（纯文本）
  model_name text not null,                 -- 使用的模型（doubao / deepseek / qwen / kimi）
  created_at timestamptz not null default now()
);

comment on table public.name_history is 'AI 起名记录：需求、方案、模型、时间';
comment on column public.name_history.model_name is '模型标识，与 modelConfigMap 的 key 一致';

-- 2. 按时间查询的索引（历史列表默认按时间倒序）
create index if not exists name_history_created_at_idx
  on public.name_history (created_at desc);

-- 3. 行级权限（RLS）
--    实验阶段：允许匿名读写，方便快速跑通
--    正式上线：改用登录用户 + 按用户隔离（见 README 的「上线前的权限收紧」）
alter table public.name_history enable row level security;

drop policy if exists "name_history_anon_insert" on public.name_history;
create policy "name_history_anon_insert"
  on public.name_history
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "name_history_anon_select" on public.name_history;
create policy "name_history_anon_select"
  on public.name_history
  for select
  to anon, authenticated
  using (true);

